create or replace function public.create_store_order(
  p_user_id uuid,
  p_guest_access_token_hash text,
  p_customer_name text,
  p_phone text,
  p_email text,
  p_shipping_address text,
  p_city text,
  p_notes text,
  p_payment_method text,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order_id uuid := gen_random_uuid();
  v_currency text;
  v_subtotal numeric(14, 4) := 0;
  v_shipping_fee numeric(14, 4) := 0;
  v_product public.products%rowtype;
  v_item jsonb;
  v_product_id uuid;
  v_quantity integer;
begin
  if (p_user_id is null) = (p_guest_access_token_hash is null) then
    raise exception 'CHECKOUT_IDENTITY_REQUIRED';
  end if;
  if length(trim(coalesce(p_customer_name, ''))) not between 2 and 200
     or length(trim(coalesce(p_phone, ''))) not between 7 and 40
     or length(trim(coalesce(p_city, ''))) not between 2 and 150
     or length(trim(coalesce(p_shipping_address, ''))) not between 3 and 1000 then
    raise exception 'INVALID_CUSTOMER_DETAILS';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
    raise exception 'INVALID_ORDER_ITEMS';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item ->> 'product_id', '') !~* '^[0-9a-f-]{36}$'
       or coalesce(v_item ->> 'quantity', '') !~ '^[0-9]{1,5}$' then
      raise exception 'INVALID_ORDER_ITEM';
    end if;
    v_product_id := (v_item ->> 'product_id')::uuid;
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity < 1 or v_quantity > 10000 then
      raise exception 'INVALID_ORDER_QUANTITY';
    end if;

    select * into v_product
    from public.products
    where id = v_product_id
    for update;
    if not found or not v_product.is_active then
      raise exception 'PRODUCT_UNAVAILABLE';
    end if;
    if v_currency is null then
      v_currency := v_product.currency;
    elsif v_currency <> v_product.currency then
      raise exception 'MIXED_CURRENCIES';
    end if;
    if v_product.product_type = 'perfume' then
      if v_product.stock_quantity < v_quantity then
        raise exception 'INSUFFICIENT_STOCK';
      end if;
      update public.products
        set stock_quantity = stock_quantity - v_quantity
        where id = v_product.id;
    end if;
    v_subtotal := v_subtotal + (v_product.price * v_quantity);
  end loop;

  if v_currency = 'USD' then
    select coalesce(shipping_fee_usd, 0) into v_shipping_fee
    from public.site_settings where id = 1;
  elsif v_currency = 'IQD' then
    select coalesce(shipping_fee_iqd, 0) into v_shipping_fee
    from public.site_settings where id = 1;
  end if;

  insert into public.orders (
    id, user_id, guest_access_token_hash, customer_name, phone, email,
    shipping_address, city, subtotal, shipping_fee, total, currency,
    payment_method, payment_status, order_status, notes
  ) values (
    v_order_id, p_user_id, p_guest_access_token_hash, trim(p_customer_name),
    trim(p_phone), nullif(trim(coalesce(p_email, '')), ''),
    trim(p_shipping_address), trim(p_city), v_subtotal, v_shipping_fee,
    v_subtotal + v_shipping_fee, v_currency,
    coalesce(nullif(trim(p_payment_method), ''), 'whatsapp'),
    'pending', 'pending_confirmation', coalesce(p_notes, '')
  );

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_product_id := (v_item ->> 'product_id')::uuid;
    v_quantity := (v_item ->> 'quantity')::integer;
    select * into v_product from public.products where id = v_product_id;
    insert into public.order_items (
      order_id, product_id, product_name, product_image,
      unit_price, quantity, line_total
    ) values (
      v_order_id, v_product.id, v_product.name, v_product.image_url,
      v_product.price, v_quantity, v_product.price * v_quantity
    );
  end loop;

  return v_order_id;
end;
$$;

